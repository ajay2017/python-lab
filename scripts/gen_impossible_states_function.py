"""Generate docs/sql/impossible-states-function.sql from Q0 in
docs/sql/impossible-states-audit.sql, so the function the maintenance cron
calls can never be a hand-retyped (drifted) copy of the audit.

    python scripts/gen_impossible_states_function.py          # rewrite the file
    python scripts/gen_impossible_states_function.py --check    # exit 1 if stale
    python scripts/gen_impossible_states_function.py --version  # print Q0_VERSION

After regenerating, re-apply the file in the Supabase SQL editor.
tests/test_impossible_states.py fails if the committed file is stale.
"""
from __future__ import annotations

import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
AUDIT = ROOT / "docs" / "sql" / "impossible-states-audit.sql"
OUT = ROOT / "docs" / "sql" / "impossible-states-function.sql"

_Q0_HEADER = "-- Q0 — SUMMARY. Run this first, alone."
_Q0_END = ") q\nORDER BY (n_bad > 0) DESC, id;"
_D4_LITERAL = (
    "     OR z.d IN (DATE '2026-01-01', DATE '2026-01-19', DATE '2026-02-16', DATE '2026-04-03',\n"
    "                DATE '2026-05-25', DATE '2026-06-19', DATE '2026-07-03', DATE '2026-09-07')"
)

_TEMPLATE = """-- =====================================================================
-- DRISHTA — impossible_states_q0(): the audit's Q0 as a callable function
-- Added 2026-10-14. APPLY ONCE in the Supabase SQL editor, and re-apply
-- after any change to Q0. Read-only: the body is a single SELECT.
--
-- The weekly maintenance cron (data_maintenance check 6) calls it through
-- PostgREST rpc, because the API client cannot run raw SQL. D4's closed-day
-- list is a PARAMETER, passed from constants.NYSE_HOLIDAYS, so the
-- function never carries a second copy of the calendar.
--
-- GENERATED by scripts/gen_impossible_states_function.py from Q0 in
-- docs/sql/impossible-states-audit.sql. Do not edit by hand; edit Q0 and
-- regenerate. tests/test_impossible_states.py fails if this file is stale.
-- =====================================================================
CREATE OR REPLACE FUNCTION public.impossible_states_q0(p_closed date[])
RETURNS TABLE(id text, chk text, n_bad bigint, n_total bigint)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $fn$
{body}
$fn$;

-- Service role only (the cron's key). Supabase grants new public-schema
-- functions to anon/authenticated by default, so revoke that explicitly.
REVOKE EXECUTE ON FUNCTION public.impossible_states_q0(date[]) FROM PUBLIC, anon, authenticated;
GRANT  EXECUTE ON FUNCTION public.impossible_states_q0(date[]) TO service_role;

-- VERIFY: 28 check rows plus one `_V` version row; counts match a manual Q0 run.
-- SELECT * FROM public.impossible_states_q0(ARRAY['2026-07-03']::date[]);
"""


def _q0_arms() -> str:
    """Q0's UNION arms (from "SELECT * FROM (" up to its closing ") q"), with
    D4's literal holiday list swapped for the p_closed parameter."""
    src = AUDIT.read_text(encoding="utf-8").replace("\r\n", "\n")
    start = src.index(_Q0_HEADER)
    body_start = src.index("SELECT * FROM (", start)
    body_end = src.index(_Q0_END, body_start)
    arms = src[body_start:body_end]
    if arms.count(_D4_LITERAL) != 1:
        raise SystemExit("Q0's D4 closed-day literal changed; update _D4_LITERAL here")
    return arms.replace(_D4_LITERAL, "     OR z.d = ANY(p_closed)")


def q0_version() -> str:
    """Short hash of the Q0 logic. The function returns it as its `_V` row and
    stock_analyzer.impossible_states.Q0_VERSION must equal it, so a function
    applied in Supabase BEFORE a Q0 edit is reported as stale -- the check-id
    set alone can't see a logic change that keeps the same ids."""
    return "q0:" + hashlib.sha256(_q0_arms().encode("utf-8")).hexdigest()[:12]


def render() -> str:
    inner = (_q0_arms().rstrip() + "\n"
             + "  UNION ALL\n"
             + f"  SELECT '_V', '{q0_version()}', NULL, NULL  -- version stamp, see q0_version()\n"
             + ") q\nORDER BY id")
    inner = "\n".join("  " + line if line else line for line in inner.splitlines())
    return _TEMPLATE.format(body=inner)


def main(argv: list[str]) -> int:
    if "--version" in argv:
        print(q0_version())
        return 0
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print(f"STALE: {OUT.relative_to(ROOT)} -- run scripts/gen_impossible_states_function.py")
            return 1
        print("up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
